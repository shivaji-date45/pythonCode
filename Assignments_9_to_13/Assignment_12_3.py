# Write a program which accepts two numbers
# and prints addition, subtraction,multiplication and division

def main():
    No1=int(input("Enter first number: "))
    No2=int(input("Enter second number: "))

    print("addition is: ",No1+No2)

    print("subtraction is: ",No1-No2)

    print("multiplication is: ",No1*No2)

    print("division is: ",No1/No2)

if __name__ == "__main__":
    main()    